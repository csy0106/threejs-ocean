const { chromium, launchOptions } = require('./test-browser.cjs');
const fs=require('node:fs');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch(launchOptions);
  const page=await browser.newPage({viewport:{width:1600,height:1000},deviceScaleFactor:1,acceptDownloads:true});
  const errors=[],checks=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  page.on('response',r=>{if(r.status()>=400)errors.push(`${r.status()} ${r.url()}`)});
  await page.goto('http://127.0.0.1:4173');
  await page.waitForFunction(()=>document.body.dataset.ready==='true');
  await page.waitForTimeout(1200);
  assert.equal(await page.evaluate(()=>oceanDemo.getState().shaderError),false);checks.push('WebGL 2 and all shaders compile');
  const time1=await page.evaluate(()=>oceanDemo.getState().time);
  await page.waitForTimeout(300);
  assert.ok((await page.evaluate(()=>oceanDemo.getState().time))>time1);checks.push('Animation advances');
  await page.locator('#pause').click();
  const pausedTime=await page.evaluate(()=>oceanDemo.getState().time);
  await page.waitForTimeout(250);
  assert.equal(await page.evaluate(()=>oceanDemo.getState().time),pausedTime);checks.push('Pause freezes the simulation');
  const setRange=async(id,value)=>page.locator('#'+id).evaluate((el,v)=>{el.value=v;el.dispatchEvent(new Event('input',{bubbles:true}));},value);
  await setRange('wave','1.15');
  assert.equal(await page.evaluate(()=>oceanDemo.uniforms.uWave.value),1.15);
  await setRange('depth','2.4');
  assert.equal(await page.evaluate(()=>oceanDemo.uniforms.uDepth.value),2.4);
  await setRange('clarity','0.55');
  assert.equal(await page.evaluate(()=>oceanDemo.uniforms.uClarity.value),0.55);
  await setRange('sun','22');
  assert.ok((await page.evaluate(()=>oceanDemo.uniforms.uSun.value.y))<0.4);checks.push('Wave, depth, clarity and sun controls update rendering');
  await page.locator('[data-preset="golden"]').click();
  assert.equal(await page.locator('#sun').inputValue(),'12');
  await page.evaluate(()=>{oceanDemo.setTime(8);oceanDemo.setView('coast',true);});
  await page.screenshot({path:'output/preview-golden.png'});checks.push('Golden-hour preset');
  await page.locator('[data-preset="breeze"]').click();
  assert.equal(await page.locator('#wave').inputValue(),'1.22');
  await page.screenshot({path:'output/preview-breeze.png'});checks.push('Breeze preset');
  await page.locator('#reset').click();
  await page.waitForTimeout(1700);
  assert.equal(await page.locator('#wave').inputValue(),'0.65');
  assert.equal(await page.locator('#depth').inputValue(),'1.2');checks.push('Reset restores default parameters and view');
  await page.evaluate(()=>oceanDemo.setTime(8));
  await page.waitForTimeout(2600);
  await page.screenshot({path:'output/preview-coast.png'});
  await page.locator('[data-view="shallow"]').click();
  await page.waitForTimeout(1600);
  assert.equal(await page.evaluate(()=>oceanDemo.getState().currentView),'shallow');
  await page.screenshot({path:'output/preview-shallow.png'});
  const causticOn=await page.evaluate(()=>document.querySelector('canvas').toDataURL());
  await setRange('caustics','0');
  await page.waitForTimeout(100);
  const causticOff=await page.evaluate(()=>document.querySelector('canvas').toDataURL());
  assert.notEqual(causticOn,causticOff);checks.push('Disabling caustics changes the rendered image');
  await setRange('caustics','1.1');
  await page.evaluate(()=>oceanDemo.setTime(8.6));
  const nextFrame=await page.evaluate(()=>document.querySelector('canvas').toDataURL());
  assert.notEqual(causticOn,nextFrame);checks.push('Water and caustics visibly change between simulation times');
  await page.evaluate(()=>oceanDemo.setTime(8));
  await page.locator('[data-view="overhead"]').click();
  await page.waitForTimeout(1600);
  await page.screenshot({path:'output/preview-overhead.png'});checks.push('All three view transitions');
  const before=await page.evaluate(()=>oceanDemo.camera.position.toArray());
  await page.mouse.move(500,400);await page.mouse.down();await page.mouse.move(650,460,{steps:12});await page.mouse.up();
  await page.waitForTimeout(300);
  assert.notDeepEqual(await page.evaluate(()=>oceanDemo.camera.position.toArray()),before);checks.push('Orbit drag moves the camera');
  await page.locator('#quality').selectOption('low');
  assert.equal(await page.evaluate(()=>oceanDemo.getState().quality),'low');
  await page.locator('#quality').selectOption('high');
  await page.waitForTimeout(200);
  assert.equal(await page.evaluate(()=>oceanDemo.getState().quality),'high');
  await page.locator('#quality').selectOption('balanced');checks.push('All quality modes');
  await page.locator('#toggle-panel').click();
  assert.ok(await page.locator('#panel').evaluate(el=>el.classList.contains('hidden')));
  await page.locator('#toggle-panel').click();checks.push('Panel visibility toggle');
  await page.evaluate(()=>{oceanDemo.setView('coast',true);oceanDemo.setTime(8);});
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#capture').click();
  const download=await downloadPromise;
  await download.saveAs('output/ocean-clean.png');
  assert.ok(fs.statSync('output/ocean-clean.png').size>100000);checks.push('PNG screenshot download');
  const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
  mobile.on('pageerror',e=>errors.push(e.message));
  await mobile.goto('http://127.0.0.1:4173');
  await mobile.waitForFunction(()=>document.body.dataset.ready==='true');
  await mobile.waitForTimeout(1000);
  assert.ok(await mobile.locator('#panel').evaluate(el=>el.classList.contains('hidden')));
  assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth),390);
  await mobile.locator('#toggle-panel').tap();
  await mobile.waitForTimeout(400);
  const bounds=await mobile.locator('#panel').boundingBox();assert.ok(bounds.x>=0&&bounds.x+bounds.width<=390);
  await mobile.screenshot({path:'output/preview-mobile.png'});checks.push('390px mobile layout and controls');
  const diagnostics=await page.evaluate(()=>{
    const gl=oceanDemo.renderer.getContext();const ext=gl.getExtension('WEBGL_debug_renderer_info');
    return {webgl:gl.getParameter(gl.VERSION),gpu:ext?gl.getParameter(ext.UNMASKED_RENDERER_WEBGL):'Unavailable',state:oceanDemo.getState()};
  });
  assert.deepEqual(errors,[]);
  const report={passed:true,checks,errors,diagnostics,checkedAt:new Date().toISOString()};
  fs.writeFileSync('output/verification.json',JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
